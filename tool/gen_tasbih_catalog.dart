String _escape(String s) {
  final out = StringBuffer();
  for (final unit in s.codeUnits) {
    if (unit >= 0x20 && unit < 0x7f && unit != 0x27 && unit != 0x5c) {
      out.writeCharCode(unit);
    } else {
      out.write('\\u${unit.toRadixString(16).padLeft(4, '0').toUpperCase()}');
    }
  }
  return out.toString();
}

void main() {
  final tassbih =
      jsonDecode(File('assets/json_data/tassbih.json').readAsStringSync())
          as Map<String, Object?>;
  final adhkar =
      jsonDecode(File('assets/json_data/adhkar.json').readAsStringSync())
          as List<Object?>;

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tasbih_catalog.dart — do not edit.')
    ..writeln('//')
    ..writeln(
      '// Each constant is a slice of the app\'s own adhkar JSON, copied',
    )
    ..writeln(
      '// code point for code point. Regenerate instead of retyping; the',
    )
    ..writeln('// reason is at the top of the generator.')
    ..writeln()
    ..writeln(
      '/// The dhikr texts the tasbih counts, exactly as the source has',
    )
    ..writeln('/// them.')
    ..writeln('abstract final class TasbihTexts {');

  for (final (i, spec) in _specs.indexed) {
    final entry = spec.read(tassbih, adhkar);
    final end = spec.end < 0 ? entry.length + spec.end : spec.end;
    final text = entry.substring(spec.start, end);
    if (text.trim() != text || text.isEmpty) {
      stderr.writeln('${spec.constName}: slice has stray whitespace: "$text"');
      exitCode = 1;
      return;
    }
    // Laid out the way `dart format` would lay it out, so formatting the
    // output is a no-op and a regenerate shows no diff.
    if (i > 0) out.writeln();
    out
      ..writeln('  /// $text')
      ..writeln('  ///')
      ..writeln('  /// ${spec.source}.json ${spec.citation}.')
      ..writeln('  static const String ${spec.constName} =')
      ..writeln("      '${_escape(text)}';");
  }
  out.writeln('}');

  const target = 'lib/features/tasbih/data/tasbih_texts.dart';
  File(target)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('wrote $target (${_specs.length} adhkar)');
}
