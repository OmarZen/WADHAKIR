// Generates lib/features/tasbih/data/tasbih_texts.dart.
//
//   dart run tool/gen_tasbih_catalog.dart
//
// Why a generator instead of typing the eight adhkar into Dart:
//
// The text has to be the SAME CODE POINTS as the app's own JSON, not just look
// the same. `tassbih.json` writes shadda before fatha (U+0651 U+064E) and is not
// even consistent about it between entries, so a retyped «إِلَّا» or «لِلَّهِ»
// renders identically and still fails an equality check. Copying by hand is how
// that slips in; slicing the source by index and range cannot.
//
// The JSON files themselves are never edited. The «تسابيح» sheet keys its
// counters by `tasbih_<text.hashCode>`, so "fixing" a diacritic there would
// silently orphan every count a user has saved against that dhikr.
//
// The output is written as `\u` escapes, so no editor, formatter or merge tool
// can normalise it on the way through.
import 'dart:convert';
import 'dart:io';

/// One dhikr: where its text lives, and which slice of that entry it is.
///
/// [start] and [end] are UTF-16 offsets into the entry's `text` — the same
/// units Dart's `substring` uses, so the test can check them the same way.
class _Spec {
  const _Spec({
    required this.constName,
    required this.source,
    required this.citation,
    required this.read,
    required this.start,
    required this.end,
  });

  final String constName;

  /// `tassbih` or `adhkar`, for the comment above the constant.
  final String source;

  /// Human-readable pointer to the entry, for the comment.
  final String citation;

  /// Pulls the entry's full text out of the decoded JSON.
  final String Function(Map<String, Object?> tassbih, List<Object?> adhkar)
  read;

  final int start;

  /// Exclusive. A negative value counts back from the end of the entry, so
  /// "the whole entry without its trailing full stop" is `-1`.
  final int end;
}

String _tassbih(Map<String, Object?> json, int index) =>
    ((json['content']! as List)[index] as Map)['text'] as String;

String _adhkar(List<Object?> json, int category, int item) =>
    (((json[category]! as Map)['array'] as List)[item] as Map)['text']
        as String;

final _specs = <_Spec>[
